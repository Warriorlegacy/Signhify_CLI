import { Subagent, SubagentTask, SubagentResult } from './types.js';

export interface PlanStep {
  id: string;
  title: string;
  subagent: 'file-picker' | 'editor' | 'reviewer' | 'browser-use';
}

export class PlannerSubagent implements Subagent {
  readonly role = 'planner';
  readonly name = '@Planner';
  readonly description = 'Formulates hierarchical task roadmaps and assigns specialized subagents';

  async run(task: SubagentTask): Promise<SubagentResult> {
    const objective = task.objective;
    const steps: PlanStep[] = [
      {
        id: 'T1',
        title: `Scope and inspect files related to: ${objective.slice(0, 50)}`,
        subagent: 'file-picker',
      },
      {
        id: 'T1.1',
        title: `Implement changes for: ${objective.slice(0, 50)}`,
        subagent: 'editor',
      },
      {
        id: 'T1.2',
        title: `Verify changes, run tests and validate stop condition`,
        subagent: 'reviewer',
      },
    ];

    const planSummary = [
      `### Roadmap Generated by @Planner for: "${objective}"`,
      ...steps.map(s => `- **[${s.id}]** ${s.title} -> Assigned to \`@${s.subagent}\``),
    ].join('\n');

    return {
      success: true,
      output: planSummary,
      metadata: { steps },
    };
  }
}

