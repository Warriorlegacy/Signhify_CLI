import { Subagent, SubagentTask, SubagentResult, SubagentContext } from './types.js';
import type { TaskNode } from '@signhify/core';
import { shouldUseAdapter, completeWithAdapter } from './llm.js';

export interface PlanStep {
  id: string;
  title: string;
  subagent: 'file-picker' | 'editor' | 'reviewer' | 'browser-use';
}

const SUBAGENT_ROLES: PlanStep['subagent'][] = ['file-picker', 'editor', 'reviewer', 'browser-use'];

/**
 * Parse a model plan out of its reply: a JSON array under a [plan] or ```json
 * fence, or anywhere in the text. Returns null when nothing usable is there —
 * the caller then falls back to the template roadmap.
 */
export function parsePlanSteps(text: string): PlanStep[] | null {
  if (!text.trim()) return null;
  const match = text.match(/\[[\s\S]*\]/);
  if (!match) return null;
  try {
    const parsed: unknown = JSON.parse(match[0]);
    if (!Array.isArray(parsed) || parsed.length === 0) return null;
    const steps: PlanStep[] = [];
    for (const item of parsed) {
      if (item === null || typeof item !== 'object') return null;
      const step = item as Record<string, unknown>;
      if (typeof step.id !== 'string' || typeof step.title !== 'string' || !step.title.trim()) return null;
      if (!SUBAGENT_ROLES.includes(step.subagent as PlanStep['subagent'])) return null;
      steps.push({ id: step.id, title: step.title, subagent: step.subagent as PlanStep['subagent'] });
    }
    return steps;
  } catch {
    return null;
  }
}

/**
 * TaskNode[] mirroring the plan: first step is the root, the rest become its
 * children — this is the `T1 → T1.n` tree the sidebar and TaskManager read.
 */
export function buildTaskNodes(steps: PlanStep[]): TaskNode[] {
  if (steps.length === 0) return [];
  const root = steps[0];
  return steps.map((step, i) => ({
    id: step.id,
    title: step.title,
    status: 'pending' as const,
    ...(i > 0 ? { parentId: root.id } : {}),
  }));
}

export class PlannerSubagent implements Subagent {
  readonly role = 'planner';
  readonly name = '@Planner';
  readonly description = 'Formulates hierarchical task roadmaps and assigns specialized subagents';

  async run(task: SubagentTask, _cwd: string, ctx?: SubagentContext): Promise<SubagentResult> {
    if (ctx?.signal?.aborted) {
      return { success: false, output: '', error: 'Subagent cancelled by user' };
    }
    const objective = task.objective;
    let steps: PlanStep[];

    if (shouldUseAdapter(ctx)) {
      const system =
        'You are @Planner, a coding-task planner. Reply with ONLY a JSON array ' +
        '(no prose) of 2-5 steps shaped [{"id":"T1","title":"...","subagent":"file-picker|editor|reviewer"}]. ' +
        'The first step scopes the work (subagent file-picker); later steps implement and verify.';
      try {
        const reply = await completeWithAdapter(
          ctx,
          system,
          `Objective: "${objective}". Existing context notes: ${JSON.stringify(task.context ?? {})}`,
        );
        const parsed = parsePlanSteps(reply);
        if (parsed) {
          steps = parsed;
        } else {
          steps = this.templateSteps(objective);
        }
      } catch (error) {
        if (ctx?.signal?.aborted) throw error;
        steps = this.templateSteps(objective);
      }
    } else {
      steps = this.templateSteps(objective);
    }

    const tasks = buildTaskNodes(steps);
    // Persist the task tree when a store is wired (tasks table, T1 → T1.n).
    for (const t of tasks) {
      ctx?.memory?.saveTask({ id: t.id, parentId: t.parentId, title: t.title, status: t.status });
    }

    const planSummary = [
      `### Roadmap Generated by @Planner for: "${objective}"`,
      ...steps.map(s => `- **[${s.id}]** ${s.title} -> Assigned to \`@${s.subagent}\``),
      ctx?.memory ? `\nPersisted ${tasks.length} task node(s) to the task tree.` : '',
    ].join('\n');

    return {
      success: true,
      output: planSummary,
      metadata: { steps, tasks },
    };
  }

  templateSteps(objective: string): PlanStep[] {
    return [
      {
        id: 'T1',
        title: `Scope and inspect files related to: ${objective.slice(0, 50)}`,
        subagent: 'file-picker',
      },
      {
        id: 'T1.1',
        title: `Implement changes for: ${objective.slice(0, 50)}`,
        subagent: 'editor',
      },
      {
        id: 'T1.2',
        title: `Verify changes, run tests and validate stop condition`,
        subagent: 'reviewer',
      },
    ];
  }
}
